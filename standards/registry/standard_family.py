"""
Типы стандартов по странам/организациям.
"""

from enum import Enum


class StandardFamily(Enum):
    """Семейства стандартов по странам/организациям."""
    ISO = "ISO"  # Международная организация по стандартизации
    DIN = "DIN"  # Немецкий институт стандартизации
    ANSI = "ANSI"  # Американский национальный институт стандартов
    ASME = "ASME"  # Американское общество инженеров-механиков
    JIS = "JIS"  # Японские промышленные стандарты
    GOST = "GOST"  # Государственные стандарты СССР/РФ
    OST = "OST"  # Отраслевые стандарты СССР/РФ
    EN = "EN"  # Европейские стандарты
    BS = "BS"  # Британские стандарты
    GB = "GB"  # Китайские национальные стандарты
