def format_list(
        items: List[str],
        title: Optional[str] = None,
        numbered: bool = False,
        bullet: str = "•"
) -> str:
    """Форматировать список."""
    lines = []

    if title:
        lines.append(f"<b>{title}</b>")
        lines.append("")

    for i, item in enumerate(items, 1 if numbered else 0):
        if numbered:
            lines.append(f"{i}. {item}")
        else:
            lines.append(f"{bullet} {item}")

    return "\n".join(lines)


def format_param(
        name: str,
        value: str,
        unit: str = "",
        highlight: bool = True,
        precision: Optional[int] = None
) -> str:
    """Форматировать параметр."""
    # Форматируем значение с учётом точности
    formatted_value = value
    if precision is not None:
        try:
            num_value = float(value)
            formatted_value = f"{num_value:.{precision}f}"
        except:
            pass

    value_text = f"<code>{formatted_value}</code>" if highlight else formatted_value
    unit_text = f" {unit}" if unit else ""
    return f"• {name}: {value_text}{unit_text}"


